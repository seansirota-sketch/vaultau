/* ============================================================
   netlify/functions/verify-survey-code.js

   Verifies the 4-digit confirmation code a student typed after
   filling out a survey campaign's Google Form. The code is
   generated by the admin panel at campaign-activation time and
   stored ONLY in survey_campaigns/{id}/secret/code — a location
   students can never read via Firestore rules. The admin pastes
   the same code into the Google Form's own "confirmation message"
   (Settings → Presentation), so Google only reveals it to a
   student AFTER they actually submit the form.

   This function is the ONLY way a target doc can transition to
   status:'done' — Firestore rules block that write from the
   client entirely (see firestore.rules), so a student cannot
   fake completion via devtools/console.

   Steps performed:
     1. Verify caller's ID token (any authenticated user).
     2. Look up the active campaign + this user's target doc.
     3. Compare the submitted code (trimmed) to the stored code.
     4. On match: mark the target doc status:'done'.

   Environment Variables:
     FIREBASE_SERVICE_ACCOUNT — JSON string of a Firebase service account key
   ============================================================ */

const admin = require('firebase-admin');

const ALLOWED_ORIGINS = (process.env.ADMIN_FUNCTION_ORIGINS ||
  'https://vaultau.netlify.app,http://localhost:8888,http://localhost:5173,http://127.0.0.1:8888'
).split(',').map(s => s.trim()).filter(Boolean);

function corsHeaders(origin) {
  const allow = ALLOWED_ORIGINS.includes(origin) ? origin : ALLOWED_ORIGINS[0];
  return {
    'Access-Control-Allow-Origin':  allow,
    'Vary':                         'Origin',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
  };
}

function getAdmin() {
  if (admin.apps.length) return admin;
  if (process.env.FIREBASE_AUTH_EMULATOR_HOST || process.env.FIRESTORE_EMULATOR_HOST) {
    admin.initializeApp({ projectId: process.env.GCLOUD_PROJECT || 'eaxmbank' });
    return admin;
  }
  const sa = process.env.FIREBASE_SERVICE_ACCOUNT;
  if (!sa) return null;
  admin.initializeApp({ credential: admin.credential.cert(JSON.parse(sa)) });
  return admin;
}

function json(statusCode, body, origin) {
  return {
    statusCode,
    headers: { ...corsHeaders(origin), 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  };
}

exports.handler = async (event) => {
  const origin = event.headers.origin || event.headers.Origin || '';
  if (event.httpMethod === 'OPTIONS') return { statusCode: 204, headers: corsHeaders(origin), body: '' };
  if (event.httpMethod !== 'POST')   return json(405, { error: 'Method Not Allowed' }, origin);

  const a = getAdmin();
  if (!a) return json(500, { error: 'Server misconfiguration (FIREBASE_SERVICE_ACCOUNT)' }, origin);

  // ── Verify caller ──
  const authHeader = event.headers.authorization || event.headers.Authorization || '';
  const idToken = authHeader.startsWith('Bearer ') ? authHeader.slice(7).trim() : '';
  if (!idToken) return json(401, { error: 'Missing Authorization bearer token' }, origin);

  let callerUid;
  try {
    const decoded = await a.auth().verifyIdToken(idToken);
    callerUid = decoded.uid;
  } catch (e) {
    return json(401, { error: 'Invalid ID token' }, origin);
  }

  // ── Parse body ──
  let body;
  try { body = JSON.parse(event.body || '{}'); }
  catch { return json(400, { error: 'Invalid JSON body' }, origin); }

  const campaignId = String(body.campaignId || '').trim();
  const code       = String(body.code       || '').trim();
  if (!campaignId || !code) {
    return json(400, { error: 'campaignId and code are required' }, origin);
  }

  const db = a.firestore();

  // ── Load campaign + confirm it's still the active one ──
  let campaign;
  try {
    const cSnap = await db.collection('survey_campaigns').doc(campaignId).get();
    if (!cSnap.exists) return json(404, { error: 'הסקר לא נמצא' }, origin);
    campaign = cSnap.data();
  } catch (e) {
    console.error('campaign lookup failed:', e);
    return json(500, { error: 'Campaign lookup failed' }, origin);
  }
  if (!campaign.active) {
    return json(400, { error: 'הסקר כבר אינו פעיל' }, origin);
  }

  // ── Load this user's target doc ──
  const targetRef = db.collection('survey_campaigns').doc(campaignId)
    .collection('targets').doc(callerUid);
  let target;
  try {
    const tSnap = await targetRef.get();
    if (!tSnap.exists) return json(403, { error: 'המשתמש אינו משויך לסקר זה' }, origin);
    target = tSnap.data();
  } catch (e) {
    console.error('target lookup failed:', e);
    return json(500, { error: 'Target lookup failed' }, origin);
  }
  if (target.status === 'done') {
    return json(200, { ok: true, alreadyDone: true }, origin);
  }

  // ── Load the secret code (never exposed to any client) ──
  let storedCode;
  try {
    const secretSnap = await db.collection('survey_campaigns').doc(campaignId)
      .collection('secret').doc('code').get();
    storedCode = secretSnap.exists ? String(secretSnap.data().code || '') : '';
  } catch (e) {
    console.error('secret lookup failed:', e);
    return json(500, { error: 'Verification lookup failed' }, origin);
  }
  if (!storedCode) {
    return json(500, { error: 'לא הוגדר קוד אימות לסקר זה — פנה למנהל המערכת' }, origin);
  }

  if (code !== storedCode) {
    return json(400, { error: 'קוד שגוי — ודא שסיימת למלא את הטופס והעתקת את הקוד המדויק מדף האישור' }, origin);
  }

  // ── Match! Mark this user's target done (only the server can do this) ──
  try {
    await targetRef.update({
      status: 'done',
      doneAt: admin.firestore.FieldValue.serverTimestamp(),
    });
  } catch (e) {
    console.error('mark done failed:', e);
    return json(500, { error: 'Failed to record completion: ' + e.message }, origin);
  }

  return json(200, { ok: true, alreadyDone: false }, origin);
};
